// Builds KroolWorldForever/Features/Transports/Data.lua from Forever's TaxiPathNode table: where
// every boat and zeppelin stops.
//
//   Invoke-WebRequest "https://wago.tools/db2/TaxiPathNode/csv?build=1.60.1.70938" -OutFile tpn.csv
//   node tools/transports-data/gen-data.js tpn.csv 1.60.1.70938
//
// A transport rides a taxi path like a flight does. Its stops are the nodes with the stop flag (2)
// and a Delay: the seconds it waits at the dock. A flight path has none. Columns used: PathID,
// NodeIndex, ContinentID, Loc_0..2 (world x, y, z), Flags, Delay.
//
// What the table cannot say: whether the server runs a path. A route that turns out not to exist
// goes in SKIP below, with the date and who saw it.
const fs = require("fs");
const path = require("path");

const [csvPath, build] = process.argv.slice(2);
if (!csvPath || !build) {
  console.error("usage: node gen-data.js <TaxiPathNode.csv> <build, e.g. 1.60.1.70938>");
  process.exit(1);
}

// Paths left out on purpose: { [PathID]: "why" }.
const SKIP = {};

const SAME_STOP = 30; // yards: one dock listed twice on a path (a round trip's start and end)

const lines = fs
  .readFileSync(csvPath, "utf8")
  .split(/\r?\n/)
  .filter((l) => l.trim() !== "");
const header = lines.shift().split(",");
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error("TaxiPathNode.csv has no column " + name);
  return i;
};
const C = {
  path: col("PathID"),
  index: col("NodeIndex"),
  continent: col("ContinentID"),
  x: col("Loc_0"),
  y: col("Loc_1"),
  z: col("Loc_2"),
  flags: col("Flags"),
  delay: col("Delay"),
};

const byPath = new Map();
for (const line of lines) {
  const f = line.split(","); // every column is a number: no quoted fields
  const node = {
    path: +f[C.path],
    index: +f[C.index],
    continent: +f[C.continent],
    x: +f[C.x],
    y: +f[C.y],
    z: +f[C.z],
    stop: (+f[C.flags] & 2) !== 0 && +f[C.delay] > 0,
  };
  if (!byPath.has(node.path)) byPath.set(node.path, []);
  byPath.get(node.path).push(node);
}

const routes = [];
for (const id of [...byPath.keys()].sort((a, b) => a - b)) {
  if (SKIP[id]) continue;
  const stops = [];
  for (const n of byPath.get(id).sort((a, b) => a.index - b.index)) {
    if (!n.stop) continue;
    const seen = stops.some((s) => s.continent === n.continent && Math.hypot(s.x - n.x, s.y - n.y) < SAME_STOP);
    if (!seen) stops.push(n);
  }
  if (stops.length >= 2) routes.push({ id, stops }); // one stop is not a trip (Naxxramas' path)
}

const num = (v) => String(Math.round(v * 10) / 10);
const out = [];
out.push("-- Generated by tools/transports-data/gen-data.js from Forever's TaxiPathNode (wago.tools,");
out.push(`-- build ${build}). Do not edit by hand.`);
out.push("-- routes[n] = { path = the taxi path the transport rides, stops = { { continent, x, y, z }, ... } }");
out.push("-- A stop is where it waits at a dock, in world coordinates. z is the deck's height: sea level");
out.push("-- for a boat, a tower's for a zeppelin.");
out.push("");
out.push("local _, root = ...");
out.push('local ns = root.Feature("transports")');
out.push("");
out.push("ns.Data = {");
out.push(`\tbuild = "${build}",`);
out.push("\troutes = {");
for (const r of routes) {
  const stops = r.stops.map((s) => `{ ${s.continent}, ${num(s.x)}, ${num(s.y)}, ${num(s.z)} }`).join(", ");
  out.push(`\t\t{ path = ${r.id}, stops = { ${stops} } },`);
}
out.push("\t},");
out.push("}");
out.push("");

const target = path.join(__dirname, "..", "..", "KroolWorldForever", "Features", "Transports", "Data.lua");
fs.mkdirSync(path.dirname(target), { recursive: true });
fs.writeFileSync(target, out.join("\n"));
console.log(`wrote ${routes.length} routes, ${routes.reduce((n, r) => n + r.stops.length, 0)} stops to ${target}`);
