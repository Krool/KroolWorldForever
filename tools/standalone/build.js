// Builds each feature of the Krool World Forever bundle as its own standalone addon, from the
// same source files, into <out>/<Folder>/.
//   node tools/standalone/build.js [--src <repo root>] [--out <dir>] [--version x.y.z] [--only <key>]
// Reads <src>/KroolWorldForever/KroolWorldForever_Forever.toc (file order, Interface, Version) and
// <src>/standalone/addons.json. Per addon it writes:
//   - the bundle's Core files in TOC order, minus Hub.lua, with Core/Identity.lua generated
//     (standalone = true, its own folder/db/slash/prefix names, the family of every sibling folder)
//   - the feature's files, and its embedded providers' files, in the bundle's TOC order
//   - <Folder>_Forever.toc and, when the manifest lists secure buttons, Bindings.xml
// New Core files and new features flow through: nothing here lists them.
const fs = require("fs");
const path = require("path");

const BUNDLE = "KroolWorldForever";

function parseArgs(argv) {
  const o = { src: path.join(__dirname, "..", ".."), out: null, version: null, only: null };
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a === "--src") o.src = path.resolve(argv[++i]);
    else if (a === "--out") o.out = path.resolve(argv[++i]);
    else if (a === "--version") o.version = argv[++i];
    else if (a === "--only") o.only = argv[++i];
    else throw new Error("unknown argument " + a);
  }
  o.out = o.out || path.join(o.src, "build", "standalone");
  return o;
}

const lua = (s) => '"' + String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"') + '"';
const luaList = (a) => "{ " + a.map(lua).join(", ") + " }";

function readToc(addonDir) {
  const text = fs.readFileSync(path.join(addonDir, BUNDLE + "_Forever.toc"), "utf8");
  const lines = text.split(/\r?\n/);
  const meta = {};
  for (const l of lines) {
    const m = l.match(/^##\s*([\w-]+):\s*(.*)$/);
    if (m) meta[m[1]] = m[2].trim();
  }
  const files = lines.map((l) => l.trim()).filter((l) => l && !l.startsWith("#"));
  return { meta, files };
}

function identityLua(e, manifest) {
  const family = [BUNDLE, ...manifest.addons.map((a) => a.folder)];
  const slashId = e.folder.toUpperCase();
  return [
    "-- GENERATED by tools/standalone/build.js from standalone/addons.json. Do not edit.",
    "-- This is the standalone " + e.folder + ": see KroolWorldForever/Core/Identity.lua for the fields.",
    "",
    "local _, root = ...",
    "",
    "root.ID = {",
    "\taddon = " + lua(e.folder) + ",",
    "\tdb = " + lua(e.db) + ",",
    "\tslashId = " + lua(slashId) + ",",
    "\tpopup = " + lua(slashId) + ",",
    "\tmainSlash = {},",
    "\tslash = " + luaList(e.slash || []) + ", -- used when the feature declares no slash words",
    "\tprefix = " + lua(e.folder) + ",",
    "\ttitle = " + lua(e.title) + ",",
    "\tchat = " + lua("|cff33ffcc" + e.title + "|r") + ",",
    "\tbundle = " + lua(BUNDLE) + ",",
    "\tfamily = " + luaList(family) + ",",
    "\tstandalone = true,",
    "\tembedded = " + luaList(e.embeddedKeys) + ",",
    "}",
    "",
  ].join("\n");
}

function tocText(e, meta, version) {
  const out = [
    "## Interface: " + meta.Interface,
    "## Title: " + e.title,
    "## Notes: " + e.notes,
    "## Author: " + (meta.Author || "Krool"),
    "## Version: " + version,
    "## Category: " + e.category,
  ];
  if (e.curseId) out.push("## X-Curse-Project-ID: " + e.curseId);
  out.push("## IconTexture: " + e.iconTexture);
  out.push("## AddonCompartmentFunc: " + e.folder + "_OnCompartmentClick");
  if (e.optionalDeps.length) out.push("## OptionalDeps: " + e.optionalDeps.join(", "));
  out.push("## SavedVariables: " + e.db, "");
  for (const f of e.files) out.push(f.replace(/\//g, "\\"));
  return out.join("\n") + "\n";
}

function bindingsXml(e) {
  const rows = e.bindings.map((b, i) => {
    const header = i === 0 ? ' header="' + e.folder.toUpperCase() + '"' : "";
    return (
      '\t<Binding name="CLICK ' + e.folder + b + ':LeftButton"' + header + ' category="ADDONS">\n\t</Binding>'
    );
  });
  return (
    "<Bindings>\n\t<!-- Generated. The secure button is made in the feature's code; its binding name and header are set there. -->\n" +
    rows.join("\n") +
    "\n</Bindings>\n"
  );
}

function build(opts) {
  const addonDir = path.join(opts.src, BUNDLE);
  const { meta, files } = readToc(addonDir);
  const manifest = JSON.parse(fs.readFileSync(path.join(opts.src, "standalone", "addons.json"), "utf8"));
  const version = opts.version || meta.Version;
  if (!meta.Interface) throw new Error("bundle TOC has no Interface line");

  // Which registry keys each Features/<Folder> declares, from its files.
  const keysOf = {};
  for (const f of files) {
    const m = f.match(/^Features[\\/]([^\\/]+)[\\/]/);
    if (!m) continue;
    const src = fs.readFileSync(path.join(addonDir, f.replace(/\\/g, "/")), "utf8");
    keysOf[m[1]] = keysOf[m[1]] || new Set();
    for (const k of src.matchAll(/root\.Feature\("(\w+)"\)/g)) keysOf[m[1]].add(k[1]);
  }

  const seen = new Set();
  const built = [];
  for (const a of manifest.addons) {
    for (const k of ["key", "folder", "title", "notes", "iconTexture", "category", "features"]) {
      if (!a[k]) throw new Error("manifest entry " + (a.key || a.folder) + " has no " + k);
    }
    if (seen.has(a.folder)) throw new Error("folder " + a.folder + " is listed twice");
    seen.add(a.folder);
    if (opts.only && a.key !== opts.only) continue;

    const e = Object.assign({ embedded: [], optionalDeps: [], bindings: [], relations: [], curseId: "" }, a);
    e.db = a.db || a.folder + "DB";
    const wanted = new Set([...e.features, ...e.embedded]);
    for (const folder of wanted) {
      if (!keysOf[folder]) throw new Error(e.folder + ": no Features/" + folder + " in the bundle TOC");
    }
    const own = e.features.some((f) => keysOf[f].has(e.key));
    if (!own) throw new Error(e.folder + ": no feature file declares key " + e.key);
    e.embeddedKeys = e.embedded.flatMap((f) => [...keysOf[f]]);

    // Core in TOC order minus the hub, then the wanted feature files; Init stays last as in the bundle.
    const core = files.filter((f) => /^Core[\\/]/.test(f) && !/Hub\.lua$/.test(f) && !/Init\.lua$/.test(f));
    const feat = files.filter((f) => {
      const m = f.match(/^Features[\\/]([^\\/]+)[\\/]/);
      return m && wanted.has(m[1]);
    });
    const init = files.filter((f) => /Init\.lua$/.test(f));
    e.files = [...core, ...feat, ...init];

    const dest = path.join(opts.out, e.folder);
    fs.rmSync(dest, { recursive: true, force: true });
    for (const f of e.files) {
      const to = path.join(dest, f.replace(/\\/g, "/"));
      fs.mkdirSync(path.dirname(to), { recursive: true });
      if (/Identity\.lua$/.test(f)) fs.writeFileSync(to, identityLua(e, manifest));
      else fs.copyFileSync(path.join(addonDir, f.replace(/\\/g, "/")), to);
    }
    fs.writeFileSync(path.join(dest, e.folder + "_Forever.toc"), tocText(e, meta, version));
    if (e.bindings.length) fs.writeFileSync(path.join(dest, "Bindings.xml"), bindingsXml(e));
    built.push(e.folder);
  }
  if (opts.only && !built.length) throw new Error("no manifest entry with key " + opts.only);
  return built;
}

if (require.main === module) {
  const opts = parseArgs(process.argv.slice(2));
  const built = build(opts);
  console.log("built " + built.length + " standalone(s) into " + opts.out + ": " + built.join(", "));
}
module.exports = { build, parseArgs };
