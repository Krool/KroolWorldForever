// Builds KroolWorldForever/Features/SkillUp/Data.lua from Forever's SkillLineAbility table: each
// recipe's yellow and grey skill (the client's own thresholds; green is halfway between).
//
//   Invoke-WebRequest "https://wago.tools/db2/SkillLineAbility/csv?build=1.60.1.70862" -OutFile sla.csv
//   node tools/skillup-data/gen-skillup.js sla.csv 1.60.1.70862
//
// Columns used: Spell (the recipe id), SkillLine (the profession), SkillupSkillLineID (its Forever
// child line), TrivialSkillLineRankLow (yellow), TrivialSkillLineRankHigh (grey). The skill-up
// CHANCE is not in any client table; the feature measures it from the player's crafts.
const fs = require("fs");
const path = require("path");

const [csvPath, build] = process.argv.slice(2);
if (!csvPath || !build) {
  console.error("usage: node gen-skillup.js <SkillLineAbility.csv> <build, e.g. 1.60.1.70862>");
  process.exit(1);
}

// RFC 4180-ish: quoted fields may hold commas, doubled quotes and newlines.
function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') {
        field += '"';
        i++;
      } else if (c === '"') {
        quoted = false;
      } else {
        field += c;
      }
    } else if (c === '"') {
      quoted = true;
    } else if (c === ",") {
      row.push(field);
      field = "";
    } else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++;
      row.push(field);
      rows.push(row);
      row = [];
      field = "";
    } else {
      field += c;
    }
  }
  if (field !== "" || row.length) {
    row.push(field);
    rows.push(row);
  }
  return rows;
}

const table = parseCsv(fs.readFileSync(csvPath, "utf8"));
const header = table.shift();
const col = (name) => {
  const i = header.indexOf(name);
  if (i < 0) throw new Error("column missing: " + name);
  return i;
};
const C = {
  spell: col("Spell"),
  line: col("SkillLine"),
  child: col("SkillupSkillLineID"),
  yellow: col("TrivialSkillLineRankLow"),
  grey: col("TrivialSkillLineRankHigh"),
};

const lines = new Map(); // profession line -> { childCounts: Map, recipes: Map spell -> {y, g, child} }
const seen = new Set();
let dupes = 0;
for (const r of table) {
  if (r.length < header.length) continue;
  const spell = Number(r[C.spell]);
  const yellow = Number(r[C.yellow]);
  const grey = Number(r[C.grey]);
  if (!spell || !(yellow > 0) || !(grey > 0)) continue;
  if (seen.has(spell)) {
    dupes++; // two spells sit in two professions; the first is kept
    continue;
  }
  seen.add(spell);
  const line = Number(r[C.line]);
  const child = Number(r[C.child]) || 0;
  if (!lines.has(line)) lines.set(line, { childCounts: new Map(), recipes: new Map() });
  const L = lines.get(line);
  L.childCounts.set(child, (L.childCounts.get(child) || 0) + 1);
  L.recipes.set(spell, { y: yellow, g: grey, child });
}

let out = "";
out += "-- Generated by tools/skillup-data/gen-skillup.js from Forever's SkillLineAbility (wago.tools,\n";
out += `-- build ${build}). Do not edit by hand.\n`;
out += "-- lines[profession skill line] = { child = its Forever child line, recipes = {\n";
out += "--   [recipe spell id] = { yellow, grey [, child line when it differs] } } }\n";
out += "-- Green starts halfway: floor((yellow + grey) / 2).\n\n";
out += "local _, root = ...\n";
out += 'local ns = root.Feature("skillup")\n\n';
out += "ns.Data = {\n";
out += `\tbuild = "${build}",\n`;
out += "\tlines = {\n";
let total = 0;
for (const [line, L] of [...lines.entries()].sort((a, b) => a[0] - b[0])) {
  let child = 0;
  let best = -1;
  for (const [c, n] of L.childCounts) {
    if (c !== 0 && n > best) {
      child = c;
      best = n;
    }
  }
  out += `\t\t[${line}] = {\n\t\t\tchild = ${child},\n\t\t\trecipes = {\n`;
  for (const [spell, v] of [...L.recipes.entries()].sort((a, b) => a[0] - b[0])) {
    const extra = v.child !== child ? `, ${v.child}` : "";
    out += `\t\t\t\t[${spell}] = { ${v.y}, ${v.g}${extra} },\n`;
    total++;
  }
  out += "\t\t\t},\n\t\t},\n";
}
out += "\t},\n}\n";

const dest = path.join(__dirname, "..", "..", "KroolWorldForever", "Features", "SkillUp", "Data.lua");
fs.mkdirSync(path.dirname(dest), { recursive: true });
fs.writeFileSync(dest, out);
console.log(`Data.lua: ${total} recipes in ${lines.size} skill lines, build ${build} (${dupes} duplicate spells skipped)`);
